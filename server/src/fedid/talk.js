// The talk-track section for the Federated Identity revoke tab, GENERATED from the same data the page shows (facts.js, story.js and the
// Mock table). scripts/build-talk-track.mjs writes it between the markers in docs/talk-track.md; a test fails if the file drifts.
import { BANNER, BANNER_DETAIL, DECK, FACTS, NOT_SAID, ROADMAP, TAGS, WHY } from './facts.js';
import { loadMock } from './mock.js';
import { STORY } from './story.js';

export const BEGIN = '<!-- fedid:begin (generated by npm run talk-track; do not edit by hand) -->';
export const END = '<!-- fedid:end -->';

export function talkTrackSection() {
  const m = loadMock();
  const b = m.final.identities.find((i) => i.state === 'revoked').summary.afterRevoke;
  const L = [];
  L.push('## Federated Identity revoke (H2 2026 update, tab "Federated Identity revoke")', '');
  L.push(`**${BANNER}.** ${BANNER_DETAIL} The banner is on every tab and in presenter mode (P, Esc to leave). Source: the deck "${DECK}", slide 40 (39 and 41 for context). Every claim below carries a tag: ${TAGS.map((t) => `\`${t}\``).join(', ')}.`, '');
  L.push('Open <http://127.0.0.1:6550/#federated-identity>. Show **Mock** first (the table is generated from the engine, the same on every machine), then switch to **Live** (the real local engine, real RS256 signing with a throwaway key) and press **Run the story**, or do the steps by hand.', '');
  L.push('### Why it matters (Ping claims from slide 40, UNVERIFIED on our tenant; challenge first)', '');
  L.push(`* **Challenge:** ${WHY.challenge}`, `* **Technical:** ${WHY.technical}`, `* **Business:** ${WHY.business}`, '');
  L.push('### The story, step by step', '');
  STORY.forEach((s, i) => L.push(`${i + 1}. ${s.t === 'revoke' ? '**REVOKE.** ' : s.t === 'issuer' ? '**ISSUER DOWN.** ' : s.t === 'advance' ? '**TIME.** ' : ''}${s.say}`));
  L.push('', '### What is cut', '');
  L.push(`Revoking \`fi-billing-agent\` cuts every service family (MCP, A2A, LLM) and the access key that names it, on the very next request. In the Mock run, ${b.refused} of ${b.requests} requests after the revoke were refused, ${b.allowed} allowed, and the first one was ${b.firstDecision.decision} (\`measured (our note)\`: counted in this lab's model, not Ping's timing). The deck says "immediately" and gives no number (\`deck claim\`); this lab reads that as "the identity state is read on every request" (\`lab reading\`).`, '');
  L.push('### What stays valid', '');
  L.push(`* The platform's token itself: ${b.tokenStillValid} of ${b.requests} post-revoke requests carried a token whose signature, binding, lifetime and expiry all passed (\`lab reading\`, \`measured (our note)\`).`);
  L.push(`* The platform keeps issuing tokens: ${b.reminted} new token(s) were minted after the revoke and refused (\`lab reading\`).`);
  L.push('* The other identity keeps working, also during an issuer outage, on the last known good key set (\`deck claim\`: refreshed every fifteen minutes, kept through outages).');
  L.push(`* Backend credentials are the application's own and the workload token is never forwarded (\`deck claim\`); forwarded in the Mock run: ${m.final.forwardedTokens} times, computed.`, '');
  L.push('### What the deck does not say', '');
  L.push('| Question | Deck | This lab | Tag |', '| --- | --- | --- | --- |');
  for (const n of NOT_SAID) L.push(`| ${n.question} | ${n.deck} | ${n.lab} | \`${n.tag}\` |`);
  L.push('', '### Roadmap, not built', '');
  for (const r of ROADMAP) L.push(`* ${r.name} (${r.what}): ${r.availability}, slide ${r.slide}. ${r.note} (\`roadmap\`)`);
  L.push('', '### Deck lines this tab rests on (all `deck claim`)', '');
  for (const f of FACTS.filter((x) => x.slide === 40)) L.push(`* ${f.text}`);
  L.push('', '### If asked', '');
  L.push('* **Is this what the product does?** No claim: the 2026-11-02 release is not on our tenant. This is a model of the deck\'s words, labelled per field.');
  L.push('* **Why does the 403 appear in the browser console?** The gateway answers the refusal with a real 403 (or 401 for a token problem); the browser logs those.');
  L.push('* **Can I type a real secret into the operator or reason field?** No: the text is masked for known secret shapes before it is stored, but that is a heuristic, not a guarantee.');
  return `${L.join('\n')}\n`;
}

export const withSection = (doc) => {
  const i = doc.indexOf(BEGIN); const j = doc.indexOf(END);
  const block = `${BEGIN}\n${talkTrackSection()}${END}`;
  return i >= 0 && j > i ? `${doc.slice(0, i)}${block}${doc.slice(j + END.length)}` : `${doc.trimEnd()}\n\n${block}\n`;
};
